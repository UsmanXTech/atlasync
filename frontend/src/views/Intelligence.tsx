import { useState } from 'react';
import { Send, Sparkles } from 'lucide-react';
import Card from '../components/Card';
import { askAtlasync, type IntelligenceSources } from '../services/intelligence';

const PRESETS = ['Are we ready to release?', 'What are the biggest risks?', 'Summarize recent cross-tool activity.'];

export default function Intelligence() {
  const [prompt, setPrompt] = useState(PRESETS[0]);
  const [answer, setAnswer] = useState('');
  const [sources, setSources] = useState<IntelligenceSources | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);

  const ask = async (text = prompt) => {
    const question = text.trim();
    if (!question || loading) return;
    setPrompt(question); setLoading(true); setError(null); setAnswer(''); setSources(null);
    const result = await askAtlasync(question);
    if (result.ok) { setAnswer(result.answer); setSources(result.sources); }
    else setError(result.error.message);
    setLoading(false);
  };

  return <div className="view">
    <div className="view-head"><h2>Intelligence</h2><p>Forge-hosted Claude analysis over permission-filtered live Jira, Confluence, and JSM context.</p></div>
    <div className="grid-2">
      <Card title="Ask Atlasync Intelligence" subtitle="Live context · read-only analysis">
        <div className="composer">
          <textarea value={prompt} onChange={(e) => setPrompt(e.target.value)} maxLength={1500} placeholder="Ask about a release, a project, or risk…" aria-label="Intelligence prompt"/>
          <div className="preset-row"><span>Try:</span>{PRESETS.map((p) => <button key={p} className="preset-btn" onClick={() => { setPrompt(p); void ask(p); }}>{p}</button>)}</div>
          <button className="btn btn-primary" onClick={() => void ask()} disabled={loading || !prompt.trim()}><Send size={14}/>{loading ? 'Analyzing live sources…' : 'Ask Atlasync'}</button>
        </div>
      </Card>
      <Card title="Source coverage" subtitle="Counts from this request’s live snapshot">
        {sources ? <div className="row-list">
          <div className="data-row"><strong>Jira issues</strong><span>{sources.jiraIssues}</span></div>
          <div className="data-row"><strong>Confluence pages</strong><span>{sources.confluencePages}</span></div>
          <div className="data-row"><strong>JSM requests</strong><span>{sources.jsmRequests}</span></div>
          {sources.unavailable.map((s) => <p className="source-error" key={s}>{s}</p>)}
        </div> : <p className="source-empty">Ask a question to fetch live context. In preview mode, the Forge backend is unavailable.</p>}
      </Card>
    </div>
    <Card title="Analysis" subtitle="Generated by Atlassian Forge LLM · verify critical decisions against source records">
      {loading && <p role="status" className="source-empty">Fetching live sources and generating the analysis…</p>}
      {error && <p role="alert" className="source-error">{error}</p>}
      {!loading && !error && !answer && <p className="source-empty">Your answer will appear here. No prefilled mock answer is presented as AI.</p>}
      {answer && <div className="ai-answer"><pre className="intelligence-answer">{answer}</pre><p className="source-footnote"><Sparkles size={13}/> AI-generated guidance may be incomplete. Atlasync does not execute actions or make release decisions.</p></div>}
    </Card>
  </div>;
}
